import { build } from "esbuild";
import { mkdir, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
const directory = new URL("../src/file-panels/source/editor/native/", import.meta.url);
const result = await build({
  entryPoints: [fileURLToPath(new URL("document.ts", directory))],
  bundle: true,
  write: false,
  format: "iife",
  platform: "browser",
  target: "es2020",
  minify: true,
  legalComments: "none",
});
const script = result.outputFiles[0].text.replace(/<\/script/gi, "<\\/script");
const html = `<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1"><meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'; connect-src 'none'; img-src 'none'; font-src 'none'; frame-src 'none'; form-action 'none'; base-uri 'none'"><style>html,body,#editor{margin:0;width:100%;height:100%;overflow:hidden}</style></head><body><div id="editor"></div><script>${script}</script></body></html>`;
const output = new URL("../generated/", directory);
await mkdir(output, { recursive: true });
await writeFile(
  new URL("native-editor.ts", output),
  `// Generated by npm run build:native-editor.\nexport default ${JSON.stringify(html)};\n`,
);
process.stdout.write(`Bundled local native editor (${Buffer.byteLength(html)} bytes)\n`);
